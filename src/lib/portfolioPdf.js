// Portfolio PDF generation — shared by the My Achievements header "More
// actions" menu, the achievement detail view and the public profile's
// export button. All entry points use the exact same documents.
import { format } from 'date-fns';

const CATEGORY_WEIGHT = { academic: 1, leadership: 2, sports: 3, arts: 4, community: 5, special: 9, behaviour: 9 };

/**
 * exportPortfolioPdf — the PUBLIC profile's portfolio export. Takes the
 * publicProfileData payload ({ student, achievements, self_reported, … }) and
 * the profile's share URL, and renders a verified-achievements PDF.
 */
export async function exportPortfolioPdf(data, shareUrl) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF();
  const student = data?.student || {};
  const achievements = data?.achievements || [];
  const selfReported = data?.self_reported || [];
  const name = student.name || 'Student';
  const left = 14;
  let y = 22;

  doc.setFontSize(22);
  doc.setTextColor(37, 99, 235);
  doc.text('BlockWard Verified Portfolio', left, y);
  y += 8;
  doc.setFontSize(11);
  doc.setTextColor(100);
  doc.text(`${name}${student.handle ? ` (@${student.handle})` : ''}`, left, y);
  if (student.grade_level) { y += 5; doc.text(`Year/Grade: ${student.grade_level}`, left, y); }
  y += 5;
  doc.text(`Generated: ${format(new Date(), 'MMM d, yyyy')}`, left, y);
  y += 4;
  doc.setDrawColor(37, 99, 235);
  doc.line(left, y, 196, y);
  y += 9;

  if (student.bio) {
    doc.setFontSize(10);
    doc.setTextColor(80);
    const bio = doc.splitTextToSize(student.bio, 180);
    doc.text(bio, left, y);
    y += bio.length * 5 + 4;
  }

  doc.setFontSize(13);
  doc.setTextColor(30);
  doc.text(`Blockward Verified achievements (${achievements.length})`, left, y);
  y += 8;

  if (achievements.length === 0) {
    doc.setFontSize(11);
    doc.setTextColor(150);
    doc.text('No verified achievements yet.', left, y);
    y += 8;
  }
  achievements.forEach((rec, idx) => {
    if (y > 262) { doc.addPage(); y = 20; }
    doc.setFontSize(12);
    doc.setTextColor(30);
    doc.text(`${idx + 1}. ${rec.title || ''}`, left, y);
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor(120);
    const meta = [
      rec.category ? `Category: ${String(rec.category).replace(/_/g, ' ')}` : '',
      rec.organisation_name ? `Issuer: ${rec.organisation_name}` : '',
      rec.date_achieved ? `Date: ${format(new Date(rec.date_achieved), 'MMM d, yyyy')}` : '',
      rec.verification_id ? `Verify ID: ${rec.verification_id}` : '',
    ].filter(Boolean).join('  |  ');
    doc.text(meta, left, y);
    y += 5;
    if (rec.description) {
      const desc = doc.splitTextToSize(rec.description, 180);
      doc.setTextColor(90);
      doc.text(desc, left, y);
      y += desc.length * 5;
    }
    if (rec.teacher_name || rec.admin_name) {
      doc.setTextColor(110);
      const sig = [
        rec.teacher_name ? `Teacher: ${rec.teacher_name}` : '',
        rec.admin_name ? `Admin: ${rec.admin_name}` : '',
      ].filter(Boolean).join('  |  ');
      doc.text(sig, left, y);
      y += 5;
    }
    y += 4;
  });

  if (selfReported.length > 0) {
    if (y > 252) { doc.addPage(); y = 20; }
    y += 2;
    doc.setFontSize(13);
    doc.setTextColor(30);
    doc.text(`Self-reported achievements (${selfReported.length})`, left, y);
    y += 4;
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text('Clearly unverified — shown for context only.', left, y);
    y += 7;
    selfReported.forEach((rec) => {
      if (y > 272) { doc.addPage(); y = 20; }
      doc.setFontSize(11);
      doc.setTextColor(60);
      doc.text(`- ${rec.title || ''}`, left, y);
      y += 6;
    });
  }

  const pages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    if (shareUrl) doc.text(`Verify at: ${shareUrl}`, left, 290);
    doc.text(`Generated by BlockWard on ${format(new Date(), 'MMM d, yyyy')}`, 196, 290, { align: 'right' });
  }

  doc.save(`BlockWard_Portfolio_${String(name).replace(/\s+/g, '_')}.pdf`);
}

/** Full / university / CV portfolio export. */
export async function exportPortfolioPDF(records, profile, user, type) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF();
  const studentName = profile ? `${profile.first_name} ${profile.last_name}` : user?.email;
  const left = 14;
  let y = 20;

  doc.setFontSize(20);
  doc.setTextColor(37, 99, 235);
  doc.text('BlockWard Portfolio', left, y);
  y += 8;
  doc.setFontSize(11);
  doc.setTextColor(100);
  const subtitle = type === 'university' ? 'University Application Portfolio'
    : type === 'cv' ? 'CV Achievement Summary'
    : 'Complete Achievement Portfolio';
  doc.text(subtitle, left, y);
  y += 6;
  doc.text(`Student: ${studentName}`, left, y);
  if (profile?.grade_level) { y += 5; doc.text(`Grade: ${profile.grade_level}`, left, y); }
  y += 5;
  doc.text(`Generated: ${format(new Date(), 'MMM d, yyyy')}`, left, y);
  y += 4;
  doc.setDrawColor(37, 99, 235);
  doc.line(left, y, 196, y);
  y += 8;

  const list = type === 'university'
    ? [...records].sort((a, b) => (CATEGORY_WEIGHT[a.category] || 9) - (CATEGORY_WEIGHT[b.category] || 9))
    : records;

  if (list.length === 0) {
    doc.setFontSize(12);
    doc.setTextColor(150);
    doc.text('No achievements to display.', left, y);
  }

  list.forEach((rec, idx) => {
    if (y > 270) { doc.addPage(); y = 20; }
    doc.setFontSize(13);
    doc.setTextColor(30);
    doc.text(`${idx + 1}. ${rec.title}`, left, y);
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor(120);
    const meta = [
      rec.category ? `Category: ${rec.category}` : '',
      rec.date_achieved ? `Date: ${format(new Date(rec.date_achieved), 'MMM d, yyyy')}` : '',
      rec.points ? `Points: ${rec.points}` : '',
      rec.verify_id ? `Verify ID: ${rec.verify_id}` : '',
    ].filter(Boolean).join('  |  ');
    doc.text(meta, left, y);
    y += 5;
    if (type !== 'cv' && rec.description) {
      const desc = doc.splitTextToSize(rec.description, 180);
      doc.setTextColor(90);
      doc.text(desc, left, y);
      y += desc.length * 5;
    }
    if (rec.teacher_name || rec.admin_name) {
      doc.setTextColor(110);
      const sig = [
        rec.teacher_name ? `Teacher: ${rec.teacher_name}` : '',
        rec.admin_name ? `Admin: ${rec.admin_name}` : '',
      ].filter(Boolean).join('  |  ');
      doc.text(sig, left, y);
      y += 5;
    }
    y += 4;
  });

  const pages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(`BlockWard — Verified Digital Portfolio  |  Page ${i} of ${pages}`, left, 290);
  }

  const fileName = `BlockWard_${type === 'university' ? 'University' : type === 'cv' ? 'CV' : 'Portfolio'}_${studentName.replace(/\s+/g, '_')}.pdf`;
  doc.save(fileName);
}

/** Single-achievement certificate download. */
export async function downloadCertificatePDF(rec, profile) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF();
  const studentName = profile ? `${profile.first_name} ${profile.last_name}` : rec.student_name;
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, 210, 40, 'F');
  doc.setTextColor(255);
  doc.setFontSize(22);
  doc.text('BlockWard Verified Achievement', 105, 25, { align: 'center' });

  doc.setTextColor(30);
  doc.setFontSize(18);
  let y = 60;
  doc.text(rec.title, 105, y, { align: 'center' });
  y += 10;
  doc.setFontSize(12);
  doc.setTextColor(100);
  doc.text(`Awarded to ${studentName}`, 105, y, { align: 'center' });
  y += 14;
  doc.setDrawColor(37, 99, 235);
  doc.line(60, y, 150, y);
  y += 12;

  doc.setFontSize(11);
  const rows = [
    ['Category', rec.category || '—'],
    ['Date Achieved', rec.date_achieved ? format(new Date(rec.date_achieved), 'MMM d, yyyy') : '—'],
    ['Points', rec.points ? String(rec.points) : '—'],
    ['Teacher', rec.teacher_name || '—'],
    ['Admin', rec.admin_name || '—'],
    ['Verification ID', rec.verify_id || '—'],
    ['Status', 'Delivered to BlockWard Vault'],
  ];
  rows.forEach(([k, v]) => {
    doc.setTextColor(120);
    doc.text(`${k}:`, 50, y);
    doc.setTextColor(40);
    doc.text(String(v), 90, y);
    y += 8;
  });

  if (rec.description) {
    y += 4;
    doc.setTextColor(120);
    doc.text('Description:', 50, y);
    y += 6;
    const desc = doc.splitTextToSize(rec.description, 120);
    doc.setTextColor(50);
    doc.text(desc, 50, y);
  }

  doc.setFontSize(9);
  doc.setTextColor(150);
  doc.text(`Verify at: ${window.location.origin}/verify/${rec.verify_id || rec.id}`, 105, 285, { align: 'center' });
  doc.text(`Generated by BlockWard on ${format(new Date(), 'MMM d, yyyy')}`, 105, 290, { align: 'center' });

  doc.save(`BlockWard_Certificate_${rec.title.replace(/[^a-zA-Z0-9]/g, '_').slice(0, 30)}.pdf`);
}